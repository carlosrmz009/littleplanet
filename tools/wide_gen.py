"""Widescreen patch table: where the stage engine assumes a 320-pixel screen, in every file that has it.

The stages (and the attract demos, which run the same engine) draw the level into the VDP's 512-pixel planes
16 pixels at a time just outside the 320-pixel screen, and leave objects off the sprite list once they are
outside it. Widescreen (src/wide.c) shows up to 108 more pixels, so those few instructions are replaced with
line-A traps that ask the emulator where the edges are this frame:

  moveq #-16,d5              left edge of a new column or row      -> $a801        d5 = left edge
  moveq #0,d5                (the full draw when a level starts)   -> $a807        d5 = left edge (and: drawn)
  move.w #$140,d5            right edge of a new column            -> $a802, nop   d5 = right edge
  moveq #$15,d6              blocks in a row, minus one            -> $a803        d6 = (right - left) / 16
  move.w d3,d1 (add.w d0,d1) object's right side on screen?        -> $a804        d1 = d3 + left extra
  cmpi.w #$140,d1            object's left side on screen?         -> $a805, nop   cmp with 320 + right extra
  move.w $8(a0),d3           x of a sprite placed on the screen    -> $a806, nop   the HUD at the left edge,
                             title cards and the rest in the middle (they stay put as the extra pixels shift)

Each site is found by the instructions around it, and a file is only listed when all of them are found and
the camera variables are where the code below expects them.

Run by tools/recomp_gen.py (the table goes with the recompiled code and is cached with it), or on its own:
usage: wide_gen.py OUT.c
"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import asm

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))
LEFT, RIGHT, ROW, OBJ_L, OBJ_R, SCREEN, FULL = 0xa801, 0xa802, 0xa803, 0xa804, 0xa805, 0xa806, 0xa807
NOP = 0x4e71
CAM_COPY = [0x4cf8, 0x00ff, 0xf700]           # movem.l ($f700).w,d0-d7: the camera, copied for the VBlank draw
CAM_COPY_TO = [0x48f9, 0x00ff, 0x00ff, 0x1926]  # movem.l d0-d7,($ff1926).l
RIGHT_BOUND = [0xb078, 0xf72a]                # cmp.w ($f72a).w,d0
LEFT_BOUND = [0xb078, 0xf728]                 # cmp.w ($f728).w,d0
FLAGS_COPY = [0x4cf8, 0x0003, 0xf754]          # movem.l ($f754).w,d0-d1: the scroll flags (bits 2, 3 of
                                              # $f754: draw plane A's column past the left, the right)


def first(w):
    return w[0] if w else None


def sites(code):
    out = []
    for i in range(2, len(code) - 2):
        off, w = code[i]
        prev, nxt = first(code[i - 1][1]), first(code[i + 1][1])
        if w == [0x7af0] and prev in (0x383c, 0x78f0, 0x6714, 0x6718):
            out.append((off, w, [LEFT]))
        elif w == [0x7a00] and (nxt == 0x3204 or (prev == 0x3801 and nxt == 0x7c1f)):
            out.append((off, w, [FULL]))
        elif w == [0x3a3c, 0x0140] and prev in (0x78f0, 0x1480):
            out.append((off, w, [RIGHT, NOP]))
        elif w == [0x3628, 0x0008] and code[i - 1][1] == [0x3428, 0x000a] and nxt >> 8 == 0x60:
            out.append((off, w, [SCREEN, NOP]))
        elif w == [0x7c15] and prev == 0x4e75:
            out.append((off, w, [ROW]))
        elif w == [0x0c41, 0x0140] and prev == 0x9240 and first(code[i + 1][1]) >> 8 == 0x6c:
            # move.w d3,d1 / add.w d0,d1 / bmi.s / move.w d3,d1 / sub.w d0,d1 / cmpi.w #$140,d1 / bge.s
            seq = [first(code[i - k][1]) for k in range(5, 0, -1)]
            if seq[0] == 0x3203 and seq[1] == 0xd240 and seq[2] >> 8 == 0x6b and seq[3] == 0x3203:
                out.append((code[i - 5][0], [0x3203], [OBJ_L]))
                out.append((off, w, [OBJ_R, NOP]))
    return out


def has(code, words):
    flat = [x for _, w in code for x in w]
    n = len(words)
    return any(flat[k:k + n] == words for k in range(len(flat) - n + 1))


def generate(assembled, out_path):   # assembled: [(file name, segments from asm.assemble)]
    files, rows = [], []
    for name, segs in assembled:
        for s in segs:
            if s['cpu'] != 'm' or int(s['base']) != 0x200000:
                continue
            code = s['code']
            found = sites(code)
            kinds = [n[0] for _, _, n in found]
            if not found:
                continue
            ok = (kinds.count(OBJ_L) == 1 and kinds.count(OBJ_R) == 1 and kinds.count(ROW) == 1 and kinds.count(SCREEN) == 1 and kinds.count(FULL) == 2
                  and kinds.count(RIGHT) >= 2 and kinds.count(LEFT) >= 6
                  and all(has(code, x) for x in (CAM_COPY, CAM_COPY_TO, RIGHT_BOUND, LEFT_BOUND, FLAGS_COPY)))
            if not ok:
                sys.exit('wide_gen: %s has the engine but not all of it (%s)' % (name, sorted(kinds)))
            files.append((name, len(rows), len(found)))
            rows += found
    if len(files) < 70:
        sys.exit('wide_gen: only %d stage files found' % len(files))
    c = ['// generated by tools/wide_gen.py from asm/: the widescreen patch sites of the stage engine',
         '#include "wide.h"', '',
         'const WideSite wide_sites[] = {']
    for off, old, new in rows:
        o = ', '.join('0x%04x' % x for x in old + [0] * (2 - len(old)))
        n = ', '.join('0x%04x' % x for x in new + [0] * (2 - len(new)))
        c.append('  { 0x%05x, %d, { %s }, { %s } },' % (off, len(old), o, n))
    c += ['};', '', 'const WideFile wide_files[] = {']
    for name, at, n in files:
        c.append('  { "%s", %d, %d },' % (name, at, n))
    c += ['};', 'const int wide_nfiles = %d;' % len(files), '']
    open(out_path, 'w').write('\n'.join(c))
    return len(files), len(rows)


def main():
    assembled = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'asm', '*.s'))):
        name, _, segs = asm.assemble(path, None)
        assembled.append((name, segs))
    print('%d stage files, %d sites' % generate(assembled, sys.argv[1]))


if __name__ == '__main__':
    main()
