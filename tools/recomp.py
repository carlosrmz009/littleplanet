"""Static recompiler: turns the disassembly's code (asm.py --code output) into C.

Every distinct instruction becomes a C function that calls the interpreter's own handler for its opcode
(m68k_ops.h, so the semantics and cycle counts are the same by construction) with the opcode and its
extension words compiled in as constants. Straight-line runs of instructions become block functions that
call them in order, checking after each one what m68k_step would check before the next (cycle budget,
pending interrupt, trace, STOP) and that execution went where it should (exceptions and HLE traps leave
the block). The game loads different code at the same addresses, so each instruction first checks that
memory holds the words it was compiled from (exactly the words the interpreter would fetch) and hands
back to the dispatcher (src/recomp.c) if not; code that matches nothing is interpreted.

Blocks don't depend on where they sit (branch targets and PC-relative operands are computed from the PC
at run time, as the interpreter does), so identical code in different files or at different addresses
is compiled once: 622k instructions in 112 files come down to about 23k blocks.

usage: recomp.py OPMAP IR_DIR OUT_DIR
  OPMAP: build/opmap.txt (tools/opmap.c), IR_DIR: tools/asm.py --code output
"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import isa68k

SPLIT = 16      # output files per kind, so the C compiles in parallel


def main():
    opmap_path, ir_dir, out_dir = sys.argv[1:4]
    opname = {}
    for line in open(opmap_path):
        k, n = line.split()
        opname[int(k, 16)] = n
    os.makedirs(out_dir, exist_ok=True)

    flow_of = {}

    def flow(words):
        if words not in flow_of:
            mem = lambda a: words[(a - 0x1000) // 2] if 0 <= (a - 0x1000) // 2 < len(words) else 0
            i = isa68k.decode(mem, 0x1000)
            flow_of[words] = i.flow if i and i.len == 2 * len(words) else 'bad'
        return flow_of[words]

    insns = {}      # words -> index
    blocks = {}     # tuple of words -> index
    entries = set() # (key, block, at)

    def add_block(cpu, blk):
        if not blk:
            return
        b = tuple(w for _, w in blk)
        if b not in blocks:
            blocks[b] = len(blocks)
            for w in b:
                insns.setdefault(w, len(insns))
        for at, (pc, _) in enumerate(blk):
            entries.add(((0 if cpu == 'm' else 1) << 24 | (pc & 0xffffff), blocks[b], at))

    nin = 0
    for f in sorted(glob.glob(os.path.join(ir_dir, '*.json'))):
        for seg in json.load(open(f)):
            blk, end = [], None
            for off, w in seg['code']:
                w = tuple(w)
                nin += 1
                if flow(w) == 'bad':      # not something the decoder agrees on: leave it to the interpreter
                    add_block(seg['cpu'], blk); blk, end = [], None
                    continue
                if blk and off != end:
                    add_block(seg['cpu'], blk); blk = []
                blk.append((seg['base'] + off, w))
                end = off + 2 * len(w)
                if flow(w) != 'seq' or len(blk) == 256:
                    add_block(seg['cpu'], blk); blk = []
            add_block(seg['cpu'], blk)

    head = ('// Generated by tools/recomp.py from asm/ -- do not edit.\n'
            '#define M68K_RECOMP\n#include "m68k_ops.h"\n#include "recomp.h"\n\n')

    # instructions: the handler with a constant opcode and constant extension words
    ins_list = sorted(insns.items(), key=lambda kv: kv[1])
    for k in range(SPLIT):
        out = [head]
        for w, i in ins_list[k::SPLIT]:
            op = w[0]
            name = opname[op]
            if len(w) > 1:
                out.append('static const u16 X%d[] = {%s};\n' % (i, ','.join('0x%04x' % x for x in w[1:])))
            out.append('void rcI%d(M68k *c) { %sc->ipc = c->pc; c->pc += 2; c->ir = 0x%04x; %s(c, 0x%04x); }\n'
                       % (i, 'c->xw = X%d; ' % i if len(w) > 1 else '', op, name, op))
        open(os.path.join(out_dir, 'rc_insn%02d.c' % k), 'w').write(''.join(out))

    # blocks
    blk_list = sorted(blocks.items(), key=lambda kv: kv[1])
    decl = ''.join('void rcI%d(M68k *c);\n' % i for _, i in ins_list)
    open(os.path.join(out_dir, 'rc_insns.h'), 'w').write('// Generated by tools/recomp.py -- do not edit.\n' + decl)
    for k in range(SPLIT):
        out = ['// Generated by tools/recomp.py from asm/ -- do not edit.\n#include "recomp.h"\n#include "rc_insns.h"\n\n']
        for b, n in blk_list[k::SPLIT]:
            out.append('void rcB%d(M68k *c, s32 lim, int at) {\n' % n)
            if len(b) > 1:
                out.append('  switch (at) {%s default: break; }\n'
                           % ''.join(' case %d: goto L%d;' % (j, j) for j in range(1, len(b))))
            for j, w in enumerate(b):
                lab = 'L%d: ' % j if j else ''
                tail = '' if j == len(b) - 1 else ' if (c->pc != c->ipc + %d) return;' % (2 * len(w))
                chk = ' && '.join('RC_W(c, %d, 0x%04x)' % (2 * k, x) for k, x in enumerate(w))
                out.append('  %sif (RC_STOP(c, lim) || !(%s)) return; rcI%d(c);%s\n' % (lab, chk, insns[w], tail))
            out.append('}\n')
        open(os.path.join(out_dir, 'rc_blocks%02d.c' % k), 'w').write(''.join(out))

    # tables: every block's words (for the check against memory) and every (cpu, pc) it can be entered at
    out = ['// Generated by tools/recomp.py from asm/ -- do not edit.\n#include "recomp.h"\n\n']
    out += ['void rcB%d(M68k *c, s32 lim, int at);\n' % n for _, n in blk_list]
    for b, n in blk_list:
        flat, starts = [], []
        for w in b:
            starts.append(len(flat))
            flat += w
        out.append('static const u16 W%d[] = {%s};\n' % (n, ','.join('0x%04x' % x for x in flat)))
        out.append('static const u16 S%d[] = {%s};\n' % (n, ','.join(map(str, starts))))
    out.append('const RcBlock rc_blocks[] = {\n')
    out += ['  {rcB%d, W%d, S%d, %d, %d},\n' % (n, n, n, sum(len(w) for w in b), len(b)) for b, n in blk_list]
    out.append('};\nconst int rc_nblocks = %d;\n' % len(blk_list))
    ent = sorted(entries)
    open(os.path.join(out_dir, 'rc_tables.c'), 'w').write(''.join(out))
    # entry points: sorted keys (cpu << 24 | address) and, for each, block << 8 | instruction
    def u32s(name, vals):
        rows = [','.join('0x%x' % v for v in vals[i:i + 12]) for i in range(0, len(vals), 12)]
        return 'const u32 %s[] = {\n%s\n};\n' % (name, ',\n'.join(rows))
    open(os.path.join(out_dir, 'rc_entries.c'), 'w').write(
        '// Generated by tools/recomp.py from asm/ -- do not edit.\n#include "recomp.h"\n\n'
        + u32s('rc_keys', [e[0] for e in ent]) + u32s('rc_vals', [e[1] << 8 | e[2] for e in ent])
        + 'const int rc_nentries = %d;\n' % len(ent))
    print('%d instructions -> %d unique instructions, %d blocks, %d entry points'
          % (nin, len(insns), len(blocks), len(ent)), file=sys.stderr)


if __name__ == '__main__':
    main()
