"""Embeds the launcher's fonts (res/fonts) as C arrays, in the order src/vg.h numbers them.
usage: embed_fonts.py OUT.c"""
import os, sys
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))
FILES = ['Archivo-ExpandedBlack.ttf', 'Archivo-CondensedBlack.ttf', 'Archivo-Bold.ttf', 'Archivo-Medium.ttf',
         'DelaGothicOne-Kana.ttf']
out = ['// Generated by tools/embed_fonts.py -- do not edit.\n']
for i, f in enumerate(FILES):
    b = open(os.path.join(ROOT, 'res', 'fonts', f), 'rb').read()
    rows = [','.join(str(x) for x in b[k:k + 40]) for k in range(0, len(b), 40)]
    out.append('static const unsigned char f%d[] = {\n%s\n};\n' % (i, ',\n'.join(rows)))
out.append('const unsigned char *const vg_font_data[%d] = {%s};\n' % (len(FILES), ', '.join('f%d' % i for i in range(len(FILES)))))
out.append('const unsigned vg_font_size[%d] = {%s};\n' % (len(FILES), ', '.join('sizeof f%d' % i for i in range(len(FILES)))))
open(sys.argv[1], 'w').write(''.join(out))
